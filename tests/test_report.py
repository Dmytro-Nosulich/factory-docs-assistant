import json

import pytest

from factory_docs.config import load_config, run_params
from factory_docs.prompts import load_prompt
from factory_docs.report import (
    END,
    START,
    comparison_section,
    latest_complete_run,
    matrix_cells,
    read_section,
    update_report,
)

DOCS = ["D001", "D002"]
CELL = ("qwen3.5-9b", "greedy", "v2")


def test_matrix_is_every_model_sampling_and_prompt_in_table_order():
    cells = matrix_cells(load_config())
    assert len(cells) == 9
    assert cells[:4] == [
        ("haiku-5.5", None, "v1"),  # the cloud model takes no sampling (I-003)
        ("haiku-5.5", None, "v2"),
        ("haiku-5.5", None, "v3"),
        ("qwen3.5-9b", "default", "v1"),
    ]
    assert cells[-1] == ("qwen3.5-9b", "greedy", "v3")


def write_summary(runs_dir, run_id, cell=CELL, **changes):
    """A run.json of `cell` that is complete with the current configuration, plus changes."""
    config = load_config()
    model_key, sampling, version = cell
    summary = {
        "run_id": run_id,
        "model": {"key": model_key},
        "prompt": {"version": version, "sha256": load_prompt("extract", version).sha256},
        "params": run_params(config, model_key, sampling),
        "max_input_tokens": config.extraction.max_input_tokens,
        "docs": DOCS,
        "counts": {"valid": 2, "invalid": 0, "error": 0, "not_run": 0},
        "finished_at": "2026-10-27T10:00:00+00:00",
        **changes,
    }
    (runs_dir / run_id).mkdir()
    (runs_dir / run_id / "run.json").write_text(json.dumps(summary), encoding="utf-8")


def test_newest_complete_run_of_the_cell_is_picked(tmp_path):
    write_summary(tmp_path, "20261021T000000Z_qwen3.5-9b_greedy_v2")
    write_summary(tmp_path, "20261027T000000Z_qwen3.5-9b_greedy_v2")
    write_summary(tmp_path, "20261028T000000Z_haiku-5.5_v2", cell=("haiku-5.5", None, "v2"))
    picked = latest_complete_run(CELL, load_config(), tmp_path, DOCS)
    assert picked == "20261027T000000Z_qwen3.5-9b_greedy_v2"


@pytest.mark.parametrize(
    "changes",
    [
        {"docs": ["D001"]},  # a DOCS subset
        {"counts": {"valid": 1, "invalid": 0, "error": 0, "not_run": 1}},  # budget stop
        {"finished_at": None},  # interrupted
        {"prompt": {"version": "v2", "sha256": "000000000000"}},  # older prompt file
        {"max_input_tokens": 1000},
    ],
)
def test_incomplete_or_stale_runs_are_not_picked(tmp_path, changes):
    write_summary(tmp_path, "20261021T000000Z_qwen3.5-9b_greedy_v2")
    write_summary(tmp_path, "20261027T000000Z_qwen3.5-9b_greedy_v2", **changes)
    picked = latest_complete_run(CELL, load_config(), tmp_path, DOCS)
    assert picked == "20261021T000000Z_qwen3.5-9b_greedy_v2"


def test_other_sampling_values_are_not_picked(tmp_path):
    params = run_params(load_config(), "qwen3.5-9b", "greedy")
    params["sampling"] = {**params["sampling"], "temperature": 0.5}  # config.toml changed since
    write_summary(tmp_path, "20261027T000000Z_qwen3.5-9b_greedy_v2", params=params)
    assert latest_complete_run(CELL, load_config(), tmp_path, DOCS) is None


def test_cells_without_a_run_are_listed(tmp_path):
    section, run_ids, missing = comparison_section(load_config(), tmp_path, DOCS)
    assert (run_ids, len(missing)) == ([], 9)
    assert "No complete run yet: haiku-5.5 v1," in section
    assert "No complete runs: run `make run`." in section


def test_update_report_keeps_the_hand_written_text(tmp_path):
    report = tmp_path / "REPORT.md"
    report.write_text(f"# Report\nby hand\n\n{START}\nold table\n{END}\n\n## Errors\nby hand\n")
    update_report(load_config(), report, runs_dir=tmp_path, doc_ids=DOCS)
    text = report.read_text()
    assert text.startswith(f"# Report\nby hand\n\n{START}\n\n")
    assert text.endswith(f"\n\n{END}\n\n## Errors\nby hand\n")
    assert "old table" not in text
    assert read_section(text).startswith("Generated by `make comparison`")


def test_update_report_without_markers_writes_nothing(tmp_path):
    report = tmp_path / "REPORT.md"
    report.write_text("# Report\nby hand\n")
    with pytest.raises(ValueError, match="no comparison markers"):
        update_report(load_config(), report, runs_dir=tmp_path, doc_ids=DOCS)
    assert report.read_text() == "# Report\nby hand\n"
