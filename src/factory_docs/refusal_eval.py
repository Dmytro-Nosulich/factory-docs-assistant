"""Measure "I don't know" on the development questions, S2-14 (rules in docs/METRICS.md).

Two signals can refuse a question:
- the score gate: the best hit's reranker score is below a threshold (no model call);
- the model: its answer says `not_in_documents`, or no answer can be shown (rejected after the
  repair, a call error, or no hit at all).
The eval answers every question with the gate off, so both signals are seen for every question,
and then scores three decisions: the model alone, the gate alone, and both combined (refused
if either refuses). The gate threshold comes only from retrieval scores, by the rule in
`pick_threshold`, so it does not depend on the prompt version.

Everything here works on the saved JSON, so `--report` rebuilds every table without models.
"""

from collections import Counter
from collections.abc import Iterable, Mapping, Sequence

from factory_docs.language import answer_text, detect
from factory_docs.metrics import percentile

START = "<!-- refusal:start (generated by `make eval-refusal`; edits here are overwritten) -->"
END = "<!-- refusal:end -->"

ANSWERED = ("answered", "partial")  # outcomes that show an answer; partial is not a refusal
DECISIONS = ("model", "gate", "combined")
DECISION_LABELS = {"model": "model only", "gate": "score gate only", "combined": "gate or model"}
UNANSWERABLE_KINDS = ("near_miss", "off_topic")

THRESHOLD_RULE = (
    "the midpoint between the lowest top-1 reranker score of an answerable question and the "
    "highest top-1 score of an unanswerable question below it, rounded to 2 decimals; no gate "
    "if no unanswerable question scores below every answerable one. So the gate refuses no "
    "answerable development question."
)


def pick_threshold(
    answerable: Iterable[float | None], unanswerable: Iterable[float | None]
) -> float | None:
    """The gate threshold by THRESHOLD_RULE; scores of questions with no hit are skipped.

    A question is refused when its top score is below the threshold, so a score equal to it
    passes. The result t keeps max(below) < t <= min(answerable).
    """
    a = [s for s in answerable if s is not None]
    u = [s for s in unanswerable if s is not None]
    if not a:
        return None
    lowest = min(a)
    below = [s for s in u if s < lowest]
    if not below:
        return None
    exact = (lowest + max(below)) / 2
    rounded = round(exact, 2)
    return rounded if max(below) < rounded <= lowest else exact


def outcome(row: Mapping) -> str:
    """answered, partial, not_in_documents (the shown answer's status), or why none is shown:
    rejected (failed the checks after the repair), error, no_context or below_threshold."""
    final = row["final_status"]
    if final in ("valid", "repaired"):
        return row["answer"]["status"]
    return "rejected" if final == "failed" else final


def answer_language(row: Mapping) -> str | None:
    """The detected language of a shown answer's claims and `missing`, None if none is shown.
    Computed from the saved answer, so `--report` uses the current detector."""
    return detect(answer_text(row["answer"])) if row["answer"] is not None else None


def gate_refuses(top_score: float | None, threshold: float | None) -> bool:
    """No hit refuses too (no_context); without a threshold the gate refuses nothing else."""
    if top_score is None:
        return True
    return threshold is not None and top_score < threshold


def refused(decision: str, question: Mapping, row: Mapping, threshold: float | None) -> bool:
    model = outcome(row) not in ANSWERED
    gate = gate_refuses(question["top_score"], threshold)
    return {"model": model, "gate": gate, "combined": model or gate}[decision]


def fraction(n: int, total: int) -> dict:
    return {"n": n, "total": total, "rate": n / total if total else None}


def rates(
    questions: Sequence[Mapping],
    rows: Mapping[str, Mapping],
    threshold: float | None,
    decision: str,
) -> dict:
    """Refusal counts of one decision. rows: question ID -> that question's run row."""
    unanswerable = [q for q in questions if q["kind"] != "answerable"]
    answerable = [q for q in questions if q["kind"] == "answerable"]

    def count(qs: Sequence[Mapping]) -> dict:
        return fraction(sum(refused(decision, q, rows[q["id"]], threshold) for q in qs), len(qs))

    languages = sorted({q["language"] for q in questions})
    return {
        "unanswerable_refused": count(unanswerable),
        "answerable_refused": count(answerable),
        "by_kind": {
            kind: count([q for q in unanswerable if q["kind"] == kind])
            for kind in UNANSWERABLE_KINDS
        },
        "by_language": {
            language: {
                "unanswerable_refused": count(
                    [q for q in unanswerable if q["language"] == language]
                ),
                "answerable_refused": count([q for q in answerable if q["language"] == language]),
            }
            for language in languages
        },
    }


def quality(questions: Sequence[Mapping], rows: Mapping[str, Mapping]) -> dict:
    """What the model's answers look like, gate off: language, sources, rejections, cost."""
    shown = [(q, rows[q["id"]]) for q in questions if rows[q["id"]]["answer"] is not None]
    answered_answerable = [
        (q, rows[q["id"]])
        for q in questions
        if q["kind"] == "answerable" and outcome(rows[q["id"]]) in ANSWERED
    ]
    right_doc = sum(
        bool(set(row["cited_docs"]) & set(q["evidence_docs"])) for q, row in answered_answerable
    )
    calls = [rows[q["id"]] for q in questions if rows[q["id"]]["total_s"] is not None]
    outcomes = Counter(outcome(rows[q["id"]]) for q in questions)
    return {
        "language_match": fraction(
            sum(answer_language(row) == q["language"] for q, row in shown), len(shown)
        ),
        "right_document": fraction(right_doc, len(answered_answerable)),
        "outcomes": dict(sorted(outcomes.items())),
        "cost_usd": sum(row["cost_usd"] for row in rows.values()),
        "latency_p50_s": percentile([r["total_s"] for r in calls], 50) if calls else None,
    }


def calls_avoided(questions: Sequence[Mapping], threshold: float | None) -> dict:
    """Questions the gate refuses before a model call (no-hit questions included)."""
    return fraction(sum(gate_refuses(q["top_score"], threshold) for q in questions), len(questions))


def summarize(data: Mapping) -> dict:
    """Every number of the report, from the saved eval JSON."""
    questions = data["questions"]
    threshold = data["threshold"]
    by_version = {}
    for version, run in data["runs"].items():
        rows = {row["id"]: row for row in run}
        by_version[version] = {
            "decisions": {d: rates(questions, rows, threshold, d) for d in DECISIONS},
            "quality": quality(questions, rows),
        }
    return {
        "threshold": threshold,
        "calls_avoided": calls_avoided(questions, threshold),
        "versions": by_version,
    }


# --- rendering ---------------------------------------------------------------------------------


def cell(f: Mapping) -> str:
    if not f["total"]:
        return "-"
    return f"{f['n']}/{f['total']} ({f['rate']:.0%})"


def score(value: float | None) -> str:
    return "-" if value is None else f"{value:.2f}"


def short(text: str, width: int = 60) -> str:
    text = " ".join(text.split()).replace("|", "/")
    return text if len(text) <= width else text[: width - 3] + "..."


def kinds_line(questions: Sequence[Mapping]) -> str:
    kinds = Counter(q["kind"] for q in questions)
    languages = Counter(q["language"] for q in questions)
    return (
        ", ".join(f"{kinds[k]} {k}" for k in ("answerable", *UNANSWERABLE_KINDS))
        + "; languages "
        + ", ".join(f"{lang} {n}" for lang, n in languages.most_common())
    )


def main_tables(data: Mapping, summary: Mapping) -> list[str]:
    settings = data["settings"]
    questions = data["questions"]
    threshold = summary["threshold"]
    gate = "no gate" if threshold is None else f"**{threshold:.2f}**"
    n_answerable = sum(q["kind"] == "answerable" for q in questions)
    n_unanswerable = len(questions) - n_answerable
    lines = [
        f"{len(questions)} development questions from `{data['dev']['path']}` "
        f"({kinds_line(questions)}). "
        f"Model `{settings['model']}`; search `{settings['collection']}`, {settings['mode']} + "
        f"rerank (`{settings['reranker']}`), best {settings['k']} hits, context budget "
        f"{settings['max_context_tokens']} estimated tokens, no filter. Every question is "
        "answered with the score gate off; the gate is applied afterwards. Rules in "
        f"docs/METRICS.md. One question is 1/{n_answerable} of an answerable rate and "
        f"1/{n_unanswerable} of an unanswerable one, so small differences are noise.",
        "",
        f"Score-gate threshold (rule fixed before the run: {THRESHOLD_RULE}): {gate}. "
        f"The gate refuses {cell(summary['calls_avoided'])} of the questions before any "
        "model call.",
        "",
        "| Prompt | Decision | Unanswerable refused | near_miss | off_topic "
        "| Answerable refused (false) |",
        "|---|---|---|---|---|---|",
    ]
    for version, result in summary["versions"].items():
        for decision in DECISIONS:
            r = result["decisions"][decision]
            lines.append(
                f"| {version} | {DECISION_LABELS[decision]} | {cell(r['unanswerable_refused'])} "
                f"| {cell(r['by_kind']['near_miss'])} | {cell(r['by_kind']['off_topic'])} "
                f"| {cell(r['answerable_refused'])} |"
            )
    lines += [
        "",
        "Answers with the gate off. Language match: claims and `missing` in the question's "
        "language (heuristic, `factory_docs.language`), over answers shown. Right document: an "
        "answered answerable question cites a chunk of its evidence document.",
        "",
        "| Prompt | Language match | Right document | Outcomes | Cost | Latency p50 |",
        "|---|---|---|---|---|---|",
    ]
    for version, result in summary["versions"].items():
        q = result["quality"]
        outcomes = ", ".join(f"{k} {n}" for k, n in q["outcomes"].items())
        latency = "-" if q["latency_p50_s"] is None else f"{q['latency_p50_s']:.1f} s"
        lines.append(
            f"| {version} | {cell(q['language_match'])} | {cell(q['right_document'])} "
            f"| {outcomes} | ${q['cost_usd']:.4f} | {latency} |"
        )
    languages = sorted({q["language"] for q in questions})
    lines += [
        "",
        "Gate or model, per question language: unanswerable refused / answerable refused.",
        "",
        "| Prompt | " + " | ".join(languages) + " |",
        "|---|" + "---|" * len(languages),
    ]
    for version, result in summary["versions"].items():
        by_language = result["decisions"]["combined"]["by_language"]
        cells = [
            f"{cell(by_language[lang]['unanswerable_refused'])} / "
            f"{cell(by_language[lang]['answerable_refused'])}"
            for lang in languages
        ]
        lines.append(f"| {version} | " + " | ".join(cells) + " |")
    return lines


def question_table(data: Mapping) -> list[str]:
    versions = list(data["runs"])
    rows = {v: {row["id"]: row for row in run} for v, run in data["runs"].items()}
    lines = [
        "| ID | Kind | Lang | Question | Top score | Evidence rank | "
        + " | ".join(f"{v} outcome | {v} lang" for v in versions)
        + " |",
        "|---|---|---|---|---|---|" + "---|---|" * len(versions),
    ]
    for q in data["questions"]:
        rank = q["evidence_rank"]
        cells = [
            f"{outcome(rows[v][q['id']])} | {answer_language(rows[v][q['id']]) or '-'}"
            for v in versions
        ]
        lines.append(
            f"| {q['id']} | {q['kind']} | {q['language']} | {short(q['question'])} "
            f"| {score(q['top_score'])} | {'-' if rank is None else rank} | "
            + " | ".join(cells)
            + " |"
        )
    return lines


def report_section(data: Mapping) -> str:
    summary = summarize(data)
    lines = main_tables(data, summary)
    lines += ["", "Per-question outcomes: [evals/results/refusal.md](evals/results/refusal.md)."]
    return "\n".join(lines) + "\n"


def markdown(data: Mapping) -> str:
    summary = summarize(data)
    prompts = ", ".join(
        f"{p['version']} (`{p['sha256'][:12]}`)" for p in data["settings"]["prompts"].values()
    )
    lines = [
        "# Refusal on the development questions (S2-14)",
        "",
        "Generated by `make eval-refusal` from `evals/results/refusal.json`; "
        "`uv run python scripts/eval_refusal.py --report` rebuilds it without models.",
        "",
        f"Run {data['created_at']} on {data['machine']['platform']}; dev file sha256 "
        f"`{data['dev']['sha256'][:12]}`; prompts {prompts}.",
        "",
        *main_tables(data, summary),
        "",
        "## Per question",
        "",
        "Top score: the best hit's reranker score (the gate compares it with the threshold). "
        "Evidence rank: the rank of the first hit holding the evidence quote among the "
        f"{data['settings']['k']} hits (answerable only; `-` when not found). Outcome with the "
        "gate off; lang: the detected language of the claims and `missing`.",
        "",
        *question_table(data),
    ]
    return "\n".join(lines) + "\n"
