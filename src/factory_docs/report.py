"""The comparison tables in REPORT.md, S1-17: one run per cell of the [comparison] matrix.

`make run` runs every cell (model x prompt version, and x sampling for a model that takes it), then
calls `update_report`; `make comparison` calls it alone, without model calls. For each cell the
tables use the newest complete run of the current configuration: the same model, sampling and
prompt version, the same prompt file (hash) and parameters, every stage 1 document and none
left `not_run`. So a run on a DOCS subset, a run stopped by the budget or a run of an older
prompt file never gets into the tables.

Only the text between the two markers in REPORT.md is generated; the rest is written by hand.
"""

import json
from pathlib import Path

from factory_docs.config import ROOT, Config, accepts_sampling, params_match, run_params
from factory_docs.golden import GOLDEN
from factory_docs.metrics import format_tables, run_metrics
from factory_docs.prompts import load_prompt
from factory_docs.run import RUNS, SUMMARY, stage1_doc_ids

REPORT = ROOT / "REPORT.md"
START = "<!-- comparison:start (generated by `make comparison`; edits here are overwritten) -->"
END = "<!-- comparison:end -->"

Cell = tuple[str, str | None, str]  # model key, sampling name (None: takes none), prompt version


def matrix_cells(config: Config) -> list[Cell]:
    """Every model x sampling x prompt version, in table order; sampling only for a model
    that takes it (Ollama models, Haiku 4.5: S1-22)."""
    comparison = config.comparison
    cells = []
    for model_key in comparison.models:
        takes_sampling = accepts_sampling(config.models[model_key])
        for sampling in comparison.sampling if takes_sampling else [None]:
            for version in comparison.prompt_versions:
                cells.append((model_key, sampling, version))
    return cells


def cell_label(cell: Cell) -> str:
    return " ".join(part for part in cell if part)


def latest_complete_run(
    cell: Cell, config: Config, runs_dir: Path = RUNS, doc_ids: list[str] | None = None
) -> str | None:
    """Run ID of the newest complete run of this cell with the current configuration, if any."""
    model_key, sampling, version = cell
    doc_ids = stage1_doc_ids() if doc_ids is None else doc_ids
    settings = config.extraction
    prompt = load_prompt(settings.prompt, version)
    params = run_params(config, model_key, sampling)
    # run IDs start with a UTC timestamp, so the name order is the time order
    for path in sorted(runs_dir.glob(f"*/{SUMMARY}"), reverse=True):
        summary = json.loads(path.read_text(encoding="utf-8"))
        if (
            summary["model"]["key"] == model_key
            and summary["prompt"]["version"] == version
            and summary["prompt"]["sha256"] == prompt.sha256
            and params_match(summary["params"], params)  # sampling name and values included
            # runs before S1-16 did not log the cap; it has been 20000 since S1-03
            and summary.get("max_input_tokens", settings.max_input_tokens)
            == settings.max_input_tokens
            and summary["docs"] == doc_ids
            and summary["counts"]["not_run"] == 0
            and summary["finished_at"]
        ):
            return summary["run_id"]
    return None


def comparison_section(
    config: Config,
    runs_dir: Path = RUNS,
    doc_ids: list[str] | None = None,
    golden_dir: Path = GOLDEN,
) -> tuple[str, list[str], list[Cell]]:
    """The generated Markdown, the run IDs it uses and the cells that have no complete run."""
    picked = {
        cell: latest_complete_run(cell, config, runs_dir, doc_ids) for cell in matrix_cells(config)
    }
    run_ids = [run_id for run_id in picked.values() if run_id]
    missing = [cell for cell, run_id in picked.items() if run_id is None]
    lines = [
        "Generated by `make comparison` (also the last step of `make run`) from the newest "
        "complete run of each configuration in `[comparison]` in `config.toml`, read from "
        "`results/runs/`; re-generating it calls no model.",
        "",
        *(f"- `{run_id}`" for run_id in run_ids),
    ]
    if missing:
        lines += ["", "No complete run yet: " + ", ".join(cell_label(c) for c in missing) + "."]
    tables = (
        format_tables([run_metrics(runs_dir / run_id, config, golden_dir) for run_id in run_ids])
        if run_ids
        else "No complete runs: run `make run`."
    )
    return "\n".join(lines) + "\n\n" + tables, run_ids, missing


def read_section(text: str) -> str:
    """The generated text between the markers, without the blank lines around it."""
    start, end = text.find(START), text.find(END)
    if start < 0 or end < start:
        raise ValueError(f"REPORT.md has no comparison markers: {START} ... {END}")
    return text[start + len(START) : end].strip("\n")


def update_report(config: Config, path: Path = REPORT, **kwargs) -> tuple[list[str], list[Cell]]:
    """Rewrite the generated section of REPORT.md; keep everything outside the markers.

    kwargs go to `comparison_section`. Returns the run IDs used and the cells with no run.
    """
    text = path.read_text(encoding="utf-8")
    read_section(text)  # fails before writing when the markers are missing
    section, run_ids, missing = comparison_section(config, **kwargs)
    start, end = text.find(START) + len(START), text.find(END)
    path.write_text(text[:start] + "\n\n" + section + "\n\n" + text[end:], encoding="utf-8")
    return run_ids, missing
