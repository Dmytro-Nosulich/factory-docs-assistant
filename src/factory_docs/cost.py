"""Cost per 1000 questions, S2-15 (rule in docs/METRICS.md, "Cost per 1000 questions").

Works on the saved `make eval-refusal` results (evals/results/refusal.json), so it needs no
model call and rebuilds the same way on a fresh clone. That eval answers every development
question with the score gate off; here the gate is applied afterwards, as `make ask` applies it:
a question whose best hit scores below `[answer] min_rerank_score` (or with no hit) gets no
model call and costs $0. Every other question costs its first call plus its repair call.

Two figures, as in stage 1: tokens x the prices in config.toml (the headline), and the cost
OpenRouter reports per call (a cross-check). Embedding and reranking run on the local CPU and
cost nothing per question; hardware and time are not counted.
"""

from collections.abc import Mapping, Sequence

from factory_docs.refusal_eval import gate_refuses

START = "<!-- cost:start (generated by `make cost`; edits here are overwritten) -->"
END = "<!-- cost:end -->"
PER = 1000


def record_tokens(record: Mapping) -> tuple[int, int]:
    """Prompt and completion tokens of an answer record: first call plus repair call, if any
    (both are paid), as `run.record_cost` sums their reported cost."""
    calls = [record.get("call"), (record.get("repair") or {}).get("call")]
    calls = [c for c in calls if c]
    return (
        sum(c.get("prompt_tokens") or 0 for c in calls),
        sum(c.get("completion_tokens") or 0 for c in calls),
    )


def tokens_usd(
    prompt_tokens: int, completion_tokens: int, price_in: float, price_out: float
) -> float:
    """Prices are USD per 1M tokens."""
    return (prompt_tokens * price_in + completion_tokens * price_out) / 1_000_000


def question_costs(
    questions: Sequence[Mapping],
    rows: Sequence[Mapping],
    threshold: float | None,
    price_in: float,
    price_out: float,
) -> list[dict]:
    """One entry per question: gated or not, its tokens and both costs ($0 when gated)."""
    by_id = {row["id"]: row for row in rows}
    out = []
    for q in questions:
        row = by_id.get(q["id"])
        if row is None:
            raise ValueError(f"no answer row for question {q['id']}")
        if "prompt_tokens" not in row or "completion_tokens" not in row:
            raise ValueError(
                f"question {q['id']}: no token counts in the saved run (saved before S2-15); "
                "run `make eval-refusal`"
            )
        gated = gate_refuses(q["top_score"], threshold)
        prompt = 0 if gated else row["prompt_tokens"] or 0
        completion = 0 if gated else row["completion_tokens"] or 0
        out.append(
            {
                "id": q["id"],
                "kind": q["kind"],
                "top_score": q["top_score"],
                "gated": gated,
                "prompt_tokens": prompt,
                "completion_tokens": completion,
                "tokens_usd": tokens_usd(prompt, completion, price_in, price_out),
                "reported_usd": 0.0 if gated else row.get("cost_usd") or 0.0,
            }
        )
    return out


def per_1000(costs: Sequence[Mapping]) -> dict:
    """1000 x the mean over `costs`, and the mean tokens per question."""
    n = len(costs)
    if not n:
        return {"n": 0}
    return {
        "n": n,
        "tokens_usd": PER * sum(c["tokens_usd"] for c in costs) / n,
        "reported_usd": PER * sum(c["reported_usd"] for c in costs) / n,
        "prompt_tokens": sum(c["prompt_tokens"] for c in costs) / n,
        "completion_tokens": sum(c["completion_tokens"] for c in costs) / n,
    }


def summarize(
    data: Mapping,
    prompt_version: str,
    threshold: float | None,
    model_key: str,
    price_in: float,
    price_out: float,
    price_checked: str,
) -> dict:
    """The cost summary of `data` (refusal.json) for one prompt version and gate threshold."""
    if not data.get("questions"):
        raise ValueError("refusal.json has no questions; run `make eval-refusal`")
    if prompt_version not in data["runs"]:
        raise ValueError(
            f"prompt {prompt_version} is not in refusal.json (has {sorted(data['runs'])}); "
            "run `make eval-refusal`"
        )
    if data["settings"]["model"] != model_key:
        raise ValueError(
            f"refusal.json was answered by {data['settings']['model']}, [answer] model is "
            f"{model_key}; run `make eval-refusal`"
        )
    costs = question_costs(
        data["questions"], data["runs"][prompt_version], threshold, price_in, price_out
    )
    return {
        "source": {"created_at": data["created_at"], "dev_sha256": data["dev"]["sha256"]},
        "model": model_key,
        "price_in_usd_per_mtok": price_in,
        "price_out_usd_per_mtok": price_out,
        "price_checked": price_checked,
        "prompt_version": prompt_version,
        "threshold": threshold,
        "unanswerable": sum(q["kind"] != "answerable" for q in data["questions"]),
        "all": per_1000(costs),
        "called": per_1000([c for c in costs if not c["gated"]]),
        "questions": costs,
    }


def money(value: float | None) -> str:
    return "-" if value is None else f"${value:.2f}"


def summary_table(s: Mapping) -> list[str]:
    a, c = s["all"], s["called"]
    gated = a["n"] - c["n"]
    return [
        "| Questions | n | Mean prompt tokens | Mean output tokens | $ / 1000 (tokens x price) "
        "| $ / 1000 (reported) |",
        "|---|---|---|---|---|---|",
        f"| All development questions ({gated} gated cost $0) | {a['n']} | - | - | "
        f"{money(a['tokens_usd'])} | {money(a['reported_usd'])} |",
        f"| Only those that reach the model | {c['n']} | "
        + (
            f"{c['prompt_tokens']:.0f} | {c['completion_tokens']:.0f} | "
            f"{money(c['tokens_usd'])} | {money(c['reported_usd'])} |"
            if c["n"]
            else "- | - | - | - |"
        ),
    ]


def intro(s: Mapping) -> list[str]:
    gate = "no gate" if s["threshold"] is None else f"score gate {s['threshold']}"
    return [
        f"Model `{s['model']}` at ${s['price_in_usd_per_mtok']:.2f} in / "
        f"${s['price_out_usd_per_mtok']:.2f} out per 1M tokens (config.toml, checked "
        f"{s['price_checked']}); prompt answer {s['prompt_version']}; {gate} "
        "(`[answer] min_rerank_score`). From the development questions in "
        f"`evals/results/refusal.json` (`make eval-refusal` run {s['source']['created_at']}), "
        "with the gate applied as `make ask` applies it: a gated question gets no model call. "
        "Each question that reaches the model costs its first call plus its repair call, if any. "
        "Rule in docs/METRICS.md.",
    ]


def caveat(s: Mapping, retrieval_link: str) -> list[str]:
    """retrieval_link: the path to evals/results/retrieval.md from the file the text goes into."""
    return [
        f"The development set is {s['unanswerable']} of {s['all']['n']} unanswerable on purpose, "
        "and gated questions cost nothing, so the first row depends on that mix. "
        "The second row is the cost of a question "
        "the model answers or refuses itself. Embedding and reranking run on the local CPU: no "
        "API cost; hardware and time are not counted (time per query: "
        f"[evals/results/retrieval.md]({retrieval_link})).",
    ]


def report_section(s: Mapping) -> str:
    lines = [
        *intro(s),
        "",
        *summary_table(s),
        "",
        *caveat(s, "../../evals/results/retrieval.md"),
        "",
        "Per question: [evals/results/cost.md](../../evals/results/cost.md).",
    ]
    return "\n".join(lines) + "\n"


def markdown(s: Mapping) -> str:
    lines = [
        "# Cost per 1000 questions (S2-15)",
        "",
        "Generated by `make cost` from `evals/results/refusal.json`, with no model calls.",
        "",
        *intro(s),
        "",
        *summary_table(s),
        "",
        *caveat(s, "retrieval.md"),
        "",
        "## Per question",
        "",
        "Top score: the best hit's reranker score. Gated: below the threshold (or no hit), so no "
        "model call. Tokens: first call plus repair call.",
        "",
        "| ID | Kind | Top score | Gated | Prompt tokens | Output tokens | $ (tokens x price) "
        "| $ (reported) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for c in s["questions"]:
        score = "-" if c["top_score"] is None else f"{c['top_score']:.2f}"
        lines.append(
            f"| {c['id']} | {c['kind']} | {score} | {'yes' if c['gated'] else 'no'} | "
            f"{c['prompt_tokens']} | {c['completion_tokens']} | ${c['tokens_usd']:.6f} | "
            f"${c['reported_usd']:.6f} |"
        )
    return "\n".join(lines) + "\n"


def one_line(s: Mapping) -> str:
    a, c = s["all"], s["called"]
    return (
        f"Cost per 1000 questions ({s['model']}, prompt {s['prompt_version']}, gate on): "
        f"{money(a['tokens_usd'])} over the {a['n']} development questions, "
        f"{money(c.get('tokens_usd'))} per 1000 that reach the model "
        f"(reported: {money(a['reported_usd'])} / {money(c.get('reported_usd'))})"
    )
