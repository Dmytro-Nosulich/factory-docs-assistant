"""Retrieval quality on the gold set, S2-10: recall@k and MRR (rules in docs/METRICS.md).

A question's rank is the 1-based position of the first returned chunk that is a hit for any of
its evidence (`retrieval_gold.is_hit`: same document, quote contained). No hit within the
search depth is a miss (rank None). recall@k is the share of questions with rank <= k; MRR is
the mean of 1 / rank, a miss counting 0. Everything here is pure, so `make eval-retrieval` and
the tests compute the numbers the same way.
"""

import time
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

from qdrant_client import QdrantClient

from factory_docs.chunking import Chunk
from factory_docs.config import RERANK_SUFFIX, SearchMode, SearchSettings
from factory_docs.embedding import Embedder
from factory_docs.index import search
from factory_docs.rerank import Reranker
from factory_docs.retrieval_gold import Question, is_hit

START = "<!-- retrieval:start (generated by `make eval-retrieval`; edits here are overwritten) -->"
END = "<!-- retrieval:end -->"


@dataclass(frozen=True)
class Setup:
    """One search setup: a first-stage mode, optionally followed by the reranker."""

    name: str
    mode: SearchMode
    rerank: bool

    @classmethod
    def parse(cls, name: str) -> "Setup":
        """'hybrid' -> hybrid without reranking; 'hybrid+rerank' -> hybrid, then reranked."""
        rerank = name.endswith(RERANK_SUFFIX)
        mode = name.removesuffix(RERANK_SUFFIX)
        if mode not in ("vector", "bm25", "hybrid"):
            raise ValueError(
                f"unknown setup {name!r}: use vector, bm25 or hybrid, +rerank optional"
            )
        return cls(name, mode, rerank)  # type: ignore[arg-type]


def first_hit_rank(chunks: Sequence[Chunk], question: Question, depth: int) -> int | None:
    """1-based rank of the first of the top `depth` chunks that answers the question."""
    for rank, chunk in enumerate(chunks[:depth], start=1):
        if any(is_hit(chunk, evidence) for evidence in question.evidence):
            return rank
    return None


def recall_at_k(ranks: Sequence[int | None], k: int) -> float:
    """Share of questions answered within the top k."""
    if not ranks:
        raise ValueError("no questions")
    return sum(rank is not None and rank <= k for rank in ranks) / len(ranks)


def hits_at_k(ranks: Sequence[int | None], k: int) -> int:
    return sum(rank is not None and rank <= k for rank in ranks)


def mrr(ranks: Sequence[int | None]) -> float:
    """Mean reciprocal rank; a miss counts 0."""
    if not ranks:
        raise ValueError("no questions")
    return sum(1 / rank for rank in ranks if rank is not None) / len(ranks)


def summary(ranks: Sequence[int | None], ks: Sequence[int]) -> dict:
    """recall@k (share and count) for each k, MRR, and the question count."""
    return {
        "questions": len(ranks),
        "recall": {str(k): recall_at_k(ranks, k) for k in ks},
        "hits": {str(k): hits_at_k(ranks, k) for k in ks},
        "mrr": mrr(ranks),
    }


def by_language(
    ranks: Mapping[str, int | None], questions: Sequence[Question], ks: Sequence[int]
) -> dict[str, dict]:
    """summary() per question language, languages in order of first appearance."""
    groups: dict[str, list[int | None]] = {}
    for question in questions:
        groups.setdefault(question.language, []).append(ranks[question.id])
    return {language: summary(group, ks) for language, group in groups.items()}


def pick_default(results: Mapping[str, dict], ks: Sequence[int], rerank: Mapping[str, bool]) -> str:
    """The default-setup rule (S2-10, written down before the run): highest MRR, then higher
    recall@5 (or the largest k below 5), then the setup without a reranker, then the name."""
    k5 = str(max((k for k in ks if k <= 5), default=min(ks)))
    return min(
        results,
        key=lambda name: (
            -round(results[name]["mrr"], 9),
            -results[name]["hits"][k5],
            rerank[name],
            name,
        ),
    )


def evaluate(
    client: QdrantClient,
    collection: str,
    questions: Sequence[Question],
    setup: Setup,
    ks: Sequence[int],
    settings: SearchSettings,
    embedder: Embedder | None,
    reranker: Reranker | None,
    candidates: int,
) -> dict:
    """Run one setup on one collection for every question, with no filter.

    Returns the summary, the per-language summaries and, per question, the rank, the IDs of
    the returned chunks and the seconds the search took.
    """
    if setup.rerank and reranker is None:
        raise ValueError(f"setup {setup.name!r} needs a reranker")
    depth = max(ks)
    per_question = {}
    for question in questions:
        start = time.perf_counter()
        hits = search(
            client,
            collection,
            question.question,
            embedder,
            depth,
            settings,
            setup.mode,
            reranker=reranker if setup.rerank else None,
            candidates=candidates,
        )
        seconds = time.perf_counter() - start
        chunks = [hit.chunk for hit in hits]
        per_question[question.id] = {
            "rank": first_hit_rank(chunks, question, depth),
            "top": [chunk.chunk_id for chunk in chunks],
            "seconds": round(seconds, 3),
        }
    ranks = {qid: result["rank"] for qid, result in per_question.items()}
    return {
        "summary": summary(list(ranks.values()), ks),
        "by_language": by_language(ranks, questions, ks),
        "questions": per_question,
    }


def replace_section(
    text: str, section: str, start_marker: str = START, end_marker: str = END
) -> str:
    """`text` with the part between the markers replaced by `section`; text outside is kept."""
    start, end = text.find(start_marker), text.find(end_marker)
    if start < 0 or end < start:
        raise ValueError(f"no markers: {start_marker} ... {end_marker}")
    start += len(start_marker)
    return text[:start] + "\n\n" + section.strip("\n") + "\n\n" + text[end:]


def update_section(
    path: Path, section: str, start_marker: str = START, end_marker: str = END
) -> None:
    text = replace_section(path.read_text(encoding="utf-8"), section, start_marker, end_marker)
    path.write_text(text, encoding="utf-8")
