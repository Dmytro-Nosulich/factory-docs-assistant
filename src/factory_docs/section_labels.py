"""Do chunk section labels name the section their text comes from? (S2-12, decision 19)

A citation names a chunk's section (`Chunk.section_path`), so the label must be right for the
text that answers. The rule (docs/METRICS.md): a label is correct for a block when it is not
empty and is a prefix of the block's section path. For a block under `SECTION 5 > 5.3` the
labels `SECTION 5` and `SECTION 5 > 5.3` are correct; `SECTION 4 > 4.3`, `SECTION 5 > 5.1` and
the empty label `(no section heading)` are not.

Two checks, neither calls a model:
- gold set: for each question, every chunk that holds an evidence quote. A question passes when
  all chunks of one of its pieces of evidence are labelled correctly.
- corpus: every (chunk, block) pair of every document. Blocks without a section are skipped,
  because there is nothing to name.
"""

