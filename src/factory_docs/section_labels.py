RETRIEVAL = ROOT / "evals" / "results" / "retrieval.json"
MARKDOWN = ROOT / "evals" / "results" / "section_labels.md"
README = ROOT / "README.md"
STRATEGIES = ("structure", "fixed")
START = "<!-- chunking:start (generated by `make section-labels`; edits here are overwritten) -->"
END = "<!-- chunking:end -->"
RETRIEVAL_SETUP = "hybrid+rerank"  # the default search setup chosen in S2-10


def label_names(label: Sequence[str], section: Sequence[str]) -> bool:
    """True when `label` is a non-empty prefix of `section`: the label names that section."""
    return bool(label) and list(section[: len(label)]) == list(label)


# Gold set
@dataclass(frozen=True)
class ChunkLabel:
    chunk_id: str
    label: str
    correct: bool


@dataclass(frozen=True)
class EvidenceLabels:
    doc_id: str
    answer_sections: tuple[tuple[str, ...], ...]  # section path of each block holding the quote
    chunks: dict[str, list[ChunkLabel]]  # collection -> the chunks that hold the quote

    def correct(self, collection: str) -> bool:
        found = self.chunks.get(collection, [])
        return bool(found) and all(chunk.correct for chunk in found)


@dataclass(frozen=True)
class QuestionLabels:
    question_id: str
    evidence: list[EvidenceLabels]

    def correct(self, collection: str) -> bool:
        return any(evidence.correct(collection) for evidence in self.evidence)


def answer_sections(document: CleanedDocument, quote: str) -> tuple[tuple[str, ...], ...]:
    """Section paths of the blocks that contain the quote, in document order, without repeats."""
    paths = [
        tuple(block.section_path)
        for block in document.blocks
        if contains_quote(render_block(block), quote)
    ]
    return tuple(dict.fromkeys(paths))


def evidence_labels(
    evidence: Evidence, document: CleanedDocument, collections: Mapping[str, Sequence[Chunk]]
) -> EvidenceLabels:
    sections = answer_sections(document, evidence.quote)
    chunks = {
        name: [
            ChunkLabel(
                chunk.chunk_id,
                chunk.section,
                any(label_names(chunk.section_path, section) for section in sections),
            )
            for chunk in items
            if is_hit(chunk, evidence)
        ]
        for name, items in collections.items()
    }
    return EvidenceLabels(evidence.doc_id, sections, chunks)


def gold_labels(
    questions: Sequence[Question],
    documents: Mapping[str, CleanedDocument],
    collections: Mapping[str, Sequence[Chunk]],
) -> list[QuestionLabels]:
    return [
        QuestionLabels(
            question.id,
            [
                evidence_labels(evidence, documents[evidence.doc_id], collections)
                for evidence in question.evidence
            ],
        )
        for question in questions
    ]


# Corpus
@dataclass(frozen=True)
class CorpusLabels:
    chunks: int
    chunks_correct: int  # chunks whose label is correct for every block with a section
    pairs: int  # (chunk, block) pairs where the block has a section
    pairs_correct: int
    skipped: int  # pairs where the block has no section


def corpus_labels(drafts: Iterable[Draft]) -> CorpusLabels:
    chunks = chunks_correct = pairs = pairs_correct = skipped = 0
    for draft in drafts:
        chunks += 1
        all_correct = True
        for block in draft.blocks:
            if not block.section_path:
                skipped += 1
                continue
            pairs += 1
            correct = label_names(draft.section_path, block.section_path)
            pairs_correct += correct
            all_correct = all_correct and correct
        chunks_correct += all_correct
    return CorpusLabels(chunks, chunks_correct, pairs, pairs_correct, skipped)


# Output
def share(part: int, whole: int, digits: int = 0) -> str:
    return f"{part} ({100 * part / whole:.{digits}f} %)" if whole else "0"


def of(part: int, whole: int, digits: int = 0) -> str:
    return f"{part} of {whole} ({100 * part / whole:.{digits}f} %)" if whole else "0 of 0"


def passed(labels: Sequence[QuestionLabels], collection: str) -> int:
    return sum(question.correct(collection) for question in labels)


def mark(chunks: Sequence[ChunkLabel]) -> str:
    if not chunks:
        return "no chunk"
    return "<br>".join(f"`{c.chunk_id}` {'✓' if c.correct else '✗'} {c.label}" for c in chunks)


def render_markdown(
    labels: Sequence[QuestionLabels],
    corpus: Mapping[str, CorpusLabels],
    collections: Sequence[str],
) -> str:
    total = len(labels)
    lines = [
        "# Section labels (S2-12)",
        "",
        "Generated by `make section-labels`; do not edit by hand.",
        "",
        "A chunk's section label is correct for a block when it is not `(no section heading)` "
        "and is a prefix of the block's section path; rules in docs/METRICS.md. No models.",
        "",
        "## Summary",
        "",
        "| Check | " + " | ".join(collections) + " |",
        "|---|" + "---|" * len(collections),
        "| Gold questions whose quote chunks all carry a correct label | "
        + " | ".join(f"{passed(labels, c)}/{total}" for c in collections)
        + " |",
        "| (chunk, block) pairs with a correct label, all documents | "
        + " | ".join(of(corpus[c].pairs_correct, corpus[c].pairs, 1) for c in collections)
        + " |",
        "| Chunks whose label is correct for every block | "
        + " | ".join(of(corpus[c].chunks_correct, corpus[c].chunks) for c in collections)
        + " |",
        "| Pairs skipped: block without a section | "
        + " | ".join(str(corpus[c].skipped) for c in collections)
        + " |",
        "",
        "A structure chunk never spans two top-level sections and is labelled with the section "
        "all its blocks share, so its pairs are correct by construction; the corpus check "
        "confirms that. A fixed chunk is labelled with the section of its first block.",
        "",
        "## Per question",
        "",
        "Every chunk that holds the evidence quote: ✓ correct label, ✗ wrong label. A question "
        "passes when all chunks of one piece of evidence are ✓.",
        "",
        "| Q | Evidence | Answer section | " + " | ".join(collections) + " |",
        "|---|---|---|" + "---|" * len(collections),
    ]
    for question in labels:
        for evidence in question.evidence:
            sections = "<br>".join(section_label(s) for s in evidence.answer_sections)
            cells = [mark(evidence.chunks.get(c, [])) for c in collections]
            lines.append(
                f"| {question.question_id} | {evidence.doc_id} | {sections} | "
                + " | ".join(cells)
                + " |"
            )
    lines.append(
        "| **Passed** | | | "
        + " | ".join(f"**{passed(labels, c)}/{total}**" for c in collections)
        + " |"
    )
    return "\n".join(lines) + "\n"


def render_readme_block(
    stats: Mapping[str, Stats],
    retrieval: Mapping[str, dict],
    labels: Sequence[QuestionLabels],
    corpus: Mapping[str, CorpusLabels],
) -> str:
    """The table for the README chunking section; every number in that section comes from here.

    stats and corpus map strategy -> its numbers; retrieval maps strategy -> the S2-10 summary
    of RETRIEVAL_SETUP (from evals/results/retrieval.json).
    """
    s, f = stats["structure"], stats["fixed"]
    rs, rf = retrieval["structure"], retrieval["fixed"]
    cs, cf = corpus["structure"], corpus["fixed"]
    total = len(labels)
    rows = [
        (
            "How it splits",
            f"whole blocks up to {MAX_CHARS} characters, inside one top-level section; closes at "
            f"a heading from {MIN_CHARS}; a chunk under {MIN_CHARS} joins a neighbour",
            f"every {MAX_CHARS} characters with {OVERLAP} characters of overlap",
        ),
        ("Chunks (69 documents)", str(s.chunks), str(f.chunks)),
        (
            "Median size, characters",
            str(percentile(list(s.sizes), 50)),
            str(percentile(list(f.sizes), 50)),
        ),
        ("Tables kept whole", of(s.tables_whole, s.tables), of(f.tables_whole, f.tables)),
        (
            "Chunks inside one top-level section",
            share(s.one_section, s.chunks),
            share(f.one_section, f.chunks),
        ),
        (
            "Chunks that start lowercase (cut mid-sentence)",
            share(s.lowercase_starts, s.chunks),
            share(f.lowercase_starts, f.chunks),
        ),
        (
            f"Chunks under {SHORT_CHARS} characters",
            share(s.short, s.chunks),
            share(f.short, f.chunks),
        ),
        (
            f"Retrieval, {RETRIEVAL_SETUP}: recall@5",
            f"{rs['hits']['5']}/{rs['questions']}",
            f"{rf['hits']['5']}/{rf['questions']}",
        ),
        (f"Retrieval, {RETRIEVAL_SETUP}: MRR@10", f"{rs['mrr']:.3f}", f"{rf['mrr']:.3f}"),
        (
            "Gold answers whose chunks all carry the right section label",
            f"{passed(labels, 'structure')}/{total}",
            f"{passed(labels, 'fixed')}/{total}",
        ),
        (
            "(chunk, block) pairs with the right section label",
            of(cs.pairs_correct, cs.pairs, 1),
            of(cf.pairs_correct, cf.pairs, 1),
        ),
        (
            "Chunks whose label is right for every block",
            share(cs.chunks_correct, cs.chunks),
            share(cf.chunks_correct, cf.chunks),
        ),
    ]
    lines = ["| | structure (used) | fixed (baseline) |", "|---|---|---|"]
    lines += [f"| {name} | {a} | {b} |" for name, a, b in rows]
    lines += [
        "",
        "Sources: chunk statistics from `make ingest` (`data/chunks/chunking_comparison.md`), "
        f"retrieval from `make eval-retrieval` on {total} gold questions "
        "(`evals/results/retrieval.md`), section labels from `make section-labels` "
        "(`evals/results/section_labels.md`).",
    ]
    return "\n".join(lines)


# Everything from the committed files
@dataclass(frozen=True)
class Outputs:
    labels: list[QuestionLabels]
    corpus: dict[str, CorpusLabels]
    markdown: str  # evals/results/section_labels.md
    readme_block: str  # the README table between START and END


def build_outputs() -> Outputs:
    """Read the gold set, cleaned documents, chunk files and retrieval results; no models."""
    collections = {
        name: load_chunks(ROOT / path) for name, path in load_config().index.collections.items()
    }
    if set(collections) != set(STRATEGIES):
        raise ValueError(f"expected collections {STRATEGIES}, config has {sorted(collections)}")
    doc_ids = {chunk.doc_id for chunks in collections.values() for chunk in chunks}
    documents = load_documents(doc_ids)
    if set(documents) != doc_ids:
        raise ValueError(f"no cleaned file for {sorted(doc_ids - set(documents))}")

    order = sorted(documents)
    drafts = {s: {d: drafts_for(documents[d], s) for d in order} for s in STRATEGIES}
    for strategy in STRATEGIES:  # the rebuilt drafts must be the chunks that were indexed
        rebuilt = [draft.text for d in order for draft in drafts[strategy][d]]
        indexed = [c.text for c in sorted(collections[strategy], key=lambda c: c.chunk_id)]
        if rebuilt != indexed:
            raise ValueError(f"{strategy}: chunks differ from the chunk file; run `make ingest`")

    stats = {s: chunk_stats((documents[d], drafts[s][d]) for d in order) for s in STRATEGIES}
    corpus = {s: corpus_labels(x for d in order for x in drafts[s][d]) for s in STRATEGIES}
    labels = gold_labels(load_gold(), documents, collections)
    runs = json.loads(RETRIEVAL.read_text(encoding="utf-8"))["runs"]
    retrieval = {s: runs[s][RETRIEVAL_SETUP]["summary"] for s in STRATEGIES}
    return Outputs(
        labels,
        corpus,
        render_markdown(labels, corpus, STRATEGIES),
        render_readme_block(stats, retrieval, labels, corpus),
    )
