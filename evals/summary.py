"""The "Results at a glance" section of REPORT.md (S2-21): headline numbers, no new metrics.

Every value is read from a result file that another make target writes, through the same summary
function that target's own REPORT section uses, so the summary cannot disagree with the sections
below it. It reads the same retrieval results and run file as `make eval-gate`. A missing input
shows as "not run yet" with the command that makes it.
"""

from collections.abc import Mapping, Sequence

from evals.answer_eval import summarize as answer_summary
from evals.calibration import summarize as calibration_summary
from evals.gate import Check
from evals.judges import QualityVerdict, SupportVerdict
from factory_docs.config import EvalGateSettings
from factory_docs.refusal_eval import cell

START = "<!-- summary:start (generated by `make report-summary`; edits here are overwritten) -->"
END = "<!-- summary:end -->"

RETRIEVAL = "[Retrieval metrics](#retrieval-metrics)"
ANSWERS = "[Answer metrics](#answer-metrics)"
CALIBRATION = "[Judge calibration](#judge-calibration)"
COST = "[Cost per 1000 questions](#cost-per-1000-questions)"


def money(value: float | None) -> str:
    return "-" if value is None else f"${value:.2f}"


def missing(command: str) -> str:
    return f"not run yet (`{command}`)"


def retrieval_rows(retrieval: Mapping | None, settings: EvalGateSettings) -> list[tuple]:
    collection, setup = settings.retrieval_collection, settings.retrieval_setup
    label = f"gold set, `{collection}` chunks, {setup}"
    run = ((retrieval or {}).get("runs") or {}).get(collection, {}).get(setup)
    if run is None:
        value = missing("make eval-retrieval")
        return [(f"Retrieval MRR@10 ({label})", value, RETRIEVAL)]
    s = run["summary"]
    recall = {"n": s["hits"]["5"], "total": s["questions"], "rate": s["recall"]["5"]}
    return [
        (f"Retrieval MRR@10 ({label})", f"{s['mrr']:.3f}", RETRIEVAL),
        (f"Retrieval recall@5 ({label})", cell(recall), RETRIEVAL),
    ]


def answer_rows(run: Mapping | None) -> list[tuple]:
    if run is None or run["settings"].get("judge") is None:
        return [("Test set, answers and judges", missing("make eval"), ANSWERS)]
    s = answer_summary(run)
    o = s["overall"]
    d, q, f = o["deterministic"], o["quality"], o["faithfulness"]
    cost = s["cost"]
    return [
        ("Test set passed (deterministic scorers)", cell(d["passed"]), ANSWERS),
        ("Unanswerable test questions refused", cell(d["unanswerable_refused"]), ANSWERS),
        (
            "Answerable and trap questions refused (lower is better)",
            cell(d["answerable_refused"]),
            ANSWERS,
        ),
        ("Quality judge: correct", cell(q[QualityVerdict.correct]), ANSWERS),
        (
            "Faithfulness judge: claims supported",
            cell(f[f"claims_{SupportVerdict.supported}"]),
            ANSWERS,
        ),
        (
            "Cost per 1000 test questions: answers / judges (score gate on)",
            f"{money(cost['answers']['usd_per_1000'])} / {money(cost['judges_usd_per_1000'])}",
            ANSWERS,
        ),
    ]


def calibration_rows(calibration: Mapping | None) -> list[tuple]:
    label = "Quality judge agrees with the hand grades"
    if calibration is None:
        return [(label, missing("make calibrate-judge"), CALIBRATION)]
    return [(label, cell(calibration_summary(calibration)["agreement"]), CALIBRATION)]


def cost_rows(cost: Mapping | None) -> list[tuple]:
    label = "Cost per 1000 questions that reach the model (development questions)"
    if cost is None or not cost["called"]["n"]:
        return [(label, missing("make cost"), COST)]
    return [(label, money(cost["called"]["reported_usd"]), COST)]


def gate_rows(checks: Sequence[Check] | None) -> list[tuple]:
    label = "CI eval gate (`make eval-gate`, thresholds in config.toml `[eval_gate]`)"
    if checks is None:
        return [(label, missing("make eval-gate"), "-")]
    ok = sum(c.ok for c in checks)
    return [(label, f"{ok}/{len(checks)} checks pass", "-")]


def section(
    settings: EvalGateSettings,
    retrieval: Mapping | None,
    run: Mapping | None,
    run_path: str | None,
    calibration: Mapping | None,
    cost: Mapping | None,
    checks: Sequence[Check] | None,
) -> str:
    rows = [
        *retrieval_rows(retrieval, settings),
        *answer_rows(run),
        *calibration_rows(calibration),
        *cost_rows(cost),
        *gate_rows(checks),
    ]
    source = f"run file `{run_path}`" if run_path else "no run file"
    lines = [
        "Headline numbers, each copied by `make report-summary` from the section it links to "
        f"(test set: {source}). Small samples: one question is 1/15 of a retrieval rate and "
        "1/24 of a test-set rate.",
        "",
        "| Measure | Value | Details |",
        "|---|---|---|",
        *(f"| {name} | {value} | {link} |" for name, value, link in rows),
    ]
    return "\n".join(lines)
