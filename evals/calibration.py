"""Judge calibration (S2-19): the quality judge against the user's hand grades.

Rules: `docs/METRICS.md`, "Judge calibration". Steps:

1. `make calibration-answers` answers the test set with the score gate off and saves the
   answers with no judge call. `sheet_markdown` writes the blind grading sheet: the same
   question, reference answer and shown answer the judge is given (`render_answer`), plus the
   judge's rules. `grades_template` writes `evals/judge_grades.toml` with every verdict empty.
2. The user grades every answer by hand, without seeing any judge verdict.
3. `make calibrate-judge` checks that every answer is graded (`grade_problems`), and only then
   runs the quality judge `PASSES` times per answer. `summarize` compares the user's grade with
   the judge's majority verdict.

Everything after the judge calls works on the saved results JSON, so `--report` rebuilds the
tables without models.
"""

import tomllib
from collections import Counter
from collections.abc import Mapping, Sequence
from pathlib import Path

from pydantic import BaseModel, ConfigDict

from evals.answer_eval import QUALITY_LABELS, settings_line
from evals.judges import NOT_JUDGED, QualityVerdict, quality_verdict, render_answer, shown_claims
from factory_docs.prompts import Prompt
from factory_docs.refusal_eval import cell, fraction, outcome, short
from factory_docs.test_set import Category, TestQuestion

START = (
    "<!-- calibration:start (generated by `make calibrate-judge`; edits here are overwritten) -->"
)
END = "<!-- calibration:end -->"

PASSES = 3  # quality judge calls per answer; the headline uses their majority verdict
NO_MAJORITY = "no_majority"  # the passes all differ
VERDICTS = tuple(v.value for v in QualityVerdict)  # correct, partially_correct, incorrect
ORDER = {"incorrect": 0, "partially_correct": 1, "correct": 2}  # for lenient vs strict
LABELS = {**QUALITY_LABELS, NO_MAJORITY: "No majority"}


# --- grades --------------------------------------------------------------------------------


class Grade(BaseModel):
    """One hand grade in `evals/judge_grades.toml`; an empty verdict is not graded yet."""

    model_config = ConfigDict(extra="forbid")

    id: str
    verdict: str = ""
    note: str = ""


def load_grades(path: Path) -> list[Grade]:
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    unknown = set(data) - {"grade"}
    if unknown:
        raise ValueError(f"{path.name}: unknown keys {sorted(unknown)}; use [[grade]] blocks")
    return [Grade(**g) for g in data.get("grade", [])]


def grade_problems(grades: Sequence[Grade], ids: Sequence[str]) -> list[str]:
    """Why the grades cannot be compared yet; [] when every answer has exactly one verdict."""
    seen = Counter(g.id for g in grades)
    problems = [f"{i}: graded {n} times" for i, n in seen.items() if n > 1]
    problems += [f"{i}: not in the calibration answers" for i in seen if i not in ids]
    problems += [f"{i}: no [[grade]] block" for i in ids if i not in seen]
    for g in grades:
        if g.id not in ids or seen[g.id] > 1:
            continue
        if not g.verdict.strip():
            problems.append(f"{g.id}: verdict is empty")
        elif g.verdict not in VERDICTS:
            problems.append(f"{g.id}: unknown verdict {g.verdict!r} (use {', '.join(VERDICTS)})")
    return problems


def grades_template(rows: Sequence[Mapping], answers_path: str, sheet_path: str) -> str:
    lines = [
        "# Hand grades of the calibration answers (S2-19). Graded by the user, by hand.",
        f"# The answers are in {answers_path}; read them in {sheet_path}.",
        "#",
        "# Grade each answer against its reference answer with the judge's rules (in the sheet),",
        "# before any judge verdict exists: `make calibrate-judge` calls the judge only when every",
        "# answer here has a verdict, and records this file's sha256.",
        "#",
        "# verdict  correct | partially_correct | incorrect",
        "# note     optional: why, in a few words (shown next to any disagreement)",
        "",
    ]
    for row in rows:
        lines += ["[[grade]]", f'id = "{row["id"]}"', 'verdict = ""', 'note = ""', ""]
    return "\n".join(lines)


# --- the blind sheet -----------------------------------------------------------------------


def rubric(prompt: Prompt) -> list[str]:
    """The judge's grading rules: its system bullets, without the reply-format ones."""
    lines = (prompt.system or "").splitlines()
    starts = [i for i, line in enumerate(lines) if line.startswith("- ")]
    ends = [i for i, line in enumerate(lines) if line.startswith("- Write `reasoning`")]
    if not starts or not ends:
        raise ValueError(f"{prompt.name} {prompt.version}: grading rules not found")
    return lines[starts[0] : ends[0]]


def sheet_markdown(
    run: Mapping, questions: Mapping[str, TestQuestion], prompt: Prompt, paths: Mapping[str, str]
) -> str:
    lines = [
        "# Judge calibration: blind grading sheet (S2-19)",
        "",
        f"Generated by `make calibration-answers` from `{paths['answers']}`. No judge has seen "
        "these answers yet.",
        "",
        settings_line(run),
        "",
        f"For each answer, write a verdict in `{paths['grades']}`: `correct`, "
        "`partially_correct` or `incorrect`, with an optional note. Grade the system answer "
        "against the reference answer by the judge's rules below. You see exactly what the "
        "judge is shown: the question, the reference answer and the shown answer (status, "
        "claims, missing; no citations).",
        "",
        f"## The judge's rules ({prompt.name} {prompt.version})",
        "",
        *rubric(prompt),
    ]
    for row in run["questions"]:
        q = questions[row["id"]]
        lines += [
            "",
            f"## {q.id} ({q.category.value}, {q.language})",
            "",
            f"**Question:** {q.question}",
            "",
            f"**Reference answer:** {q.expected_answer}",
            "",
            "**System answer:**",
            "",
            "```text",
            render_answer(row),
            "```",
        ]
    return "\n".join(lines) + "\n"


# --- agreement -----------------------------------------------------------------------------


def majority(verdicts: Sequence[str]) -> str:
    """The verdict of more than half of the passes, else no_majority."""
    level, n = Counter(verdicts).most_common(1)[0]
    return level if 2 * n > len(verdicts) else NO_MAJORITY


def cohen_kappa(a: Sequence[str], b: Sequence[str]) -> float | None:
    """Unweighted Cohen's kappa of two raters; None when chance agreement is 1."""
    n = len(a)
    if not n:
        return None
    observed = sum(x == y for x, y in zip(a, b, strict=True)) / n
    ca, cb = Counter(a), Counter(b)
    chance = sum(ca[k] * cb[k] for k in ca) / n**2
    return None if chance == 1 else (observed - chance) / (1 - chance)


def direction(human: Sequence[str], judge: Sequence[str]) -> dict:
    """Disagreements: judge graded higher (lenient), lower (strict), or gave no verdict."""
    out = {"disagreements": 0, "lenient": 0, "strict": 0, "no_verdict": 0}
    for h, j in zip(human, judge, strict=True):
        if h == j:
            continue
        out["disagreements"] += 1
        if j not in ORDER:
            out["no_verdict"] += 1
        elif ORDER[j] > ORDER[h]:
            out["lenient"] += 1
        else:
            out["strict"] += 1
    return out


def confusion(human: Sequence[str], judge: Sequence[str]) -> dict:
    """{human verdict: {judge verdict: n}}, with not_judged and no_majority columns."""
    columns = (*VERDICTS, NOT_JUDGED, NO_MAJORITY)
    table = {h: dict.fromkeys(columns, 0) for h in VERDICTS}
    for h, j in zip(human, judge, strict=True):
        table[h][j] += 1
    return table


def pass_verdicts(row: Mapping) -> list[str]:
    return [quality_verdict(j) for j in row["judge"]]


def summarize(result: Mapping) -> dict:
    rows = result["questions"]
    human = [r["human"]["verdict"] for r in rows]
    passes = [pass_verdicts(r) for r in rows]
    judge = [majority(p) for p in passes]
    n_passes = len(passes[0]) if passes else 0

    def agree(idx: Sequence[int]) -> dict:
        return fraction(sum(human[i] == judge[i] for i in idx), len(idx))

    every = range(len(rows))
    with_claims = [i for i in every if rows[i]["has_claims"]]
    no_claims = [i for i in every if not rows[i]["has_claims"]]
    judgements = [j for r in rows for j in r["judge"]]
    return {
        "n": len(rows),
        "passes": n_passes,
        "agreement": agree(every),
        "agreement_with_claims": agree(with_claims),
        "agreement_no_claims": agree(no_claims),
        "kappa": cohen_kappa(human, judge),
        "binary": fraction(
            sum((h == "correct") == (j == "correct") for h, j in zip(human, judge, strict=True)),
            len(rows),
        ),
        "per_pass": [
            fraction(sum(h == p[k] for h, p in zip(human, passes, strict=True)), len(rows))
            for k in range(n_passes)
        ],
        "consistent": fraction(sum(len(set(p)) == 1 for p in passes), len(rows)),
        "direction": direction(human, judge),
        "confusion": confusion(human, judge),
        "human_counts": {v: human.count(v) for v in VERDICTS},
        "judge_counts": {v: judge.count(v) for v in (*VERDICTS, NOT_JUDGED, NO_MAJORITY)},
        "by_category": {
            c.value: agree([i for i in every if rows[i]["category"] == c.value])
            for c in Category
            if any(r["category"] == c.value for r in rows)
        },
        "cost": {
            "calls": sum(j["record"] is not None for j in judgements),
            "prompt_tokens": sum(j["prompt_tokens"] or 0 for j in judgements),
            "completion_tokens": sum(j["completion_tokens"] or 0 for j in judgements),
            "usd": sum(j["cost_usd"] for j in judgements),
        },
    }


# --- report --------------------------------------------------------------------------------


def kappa_text(kappa: float | None) -> str:
    return "-" if kappa is None else f"{kappa:.2f}"


def headline(summary: Mapping) -> str:
    return (
        f"**The judge agrees with the hand grade on {cell(summary['agreement'])} of the "
        f"answers** (majority of {summary['passes']} passes, 3 levels); Cohen's kappa "
        f"{kappa_text(summary['kappa'])}."
    )


def measures_table(summary: Mapping) -> list[str]:
    d = summary["direction"]
    lines = [
        "| Measure | Value |",
        "|---|---|",
        f"| Exact agreement, all answers (headline) | {cell(summary['agreement'])} |",
        f"| Exact agreement, answers with claims | {cell(summary['agreement_with_claims'])} |",
        f"| Exact agreement, refusals (no claims) | {cell(summary['agreement_no_claims'])} |",
        f"| Cohen's kappa (3 levels, judge majority) | {kappa_text(summary['kappa'])} |",
        f"| Binary agreement (correct vs not correct) | {cell(summary['binary'])} |",
    ]
    lines += [
        f"| Exact agreement, pass {k} alone | {cell(f)} |"
        for k, f in enumerate(summary["per_pass"], start=1)
    ]
    lines += [
        f"| Judge gives the same verdict in all {summary['passes']} passes | "
        f"{cell(summary['consistent'])} |",
        f"| Disagreements: judge higher (lenient) / lower (strict) / no verdict | "
        f"{d['lenient']} / {d['strict']} / {d['no_verdict']} of {d['disagreements']} |",
    ]
    return lines


def confusion_table(summary: Mapping) -> list[str]:
    columns = [
        c
        for c in (*VERDICTS, NOT_JUDGED, NO_MAJORITY)
        if c in VERDICTS or any(row[c] for row in summary["confusion"].values())
    ]
    lines = [
        "| Hand grade \\ judge majority | " + " | ".join(LABELS[c] for c in columns) + " | Total |",
        "|---|" + "---|" * (len(columns) + 1),
    ]
    for h, row in summary["confusion"].items():
        cells = " | ".join(str(row[c]) for c in columns)
        lines.append(f"| {LABELS[h]} | {cells} | {sum(row.values())} |")
    totals = " | ".join(str(summary["judge_counts"][c]) for c in columns)
    lines.append(f"| Total | {totals} | {summary['n']} |")
    return lines


def category_table(summary: Mapping) -> list[str]:
    lines = ["| Category | Exact agreement |", "|---|---|"]
    lines += [f"| {c} | {cell(f)} |" for c, f in summary["by_category"].items()]
    return lines


def main_tables(summary: Mapping) -> list[str]:
    return [
        headline(summary),
        "",
        *measures_table(summary),
        "",
        "Hand grade against the judge's majority verdict, in answers:",
        "",
        *confusion_table(summary),
        "",
        *category_table(summary),
    ]


def question_table(result: Mapping) -> list[str]:
    lines = [
        "| ID | Category | Lang | Question | Outcome | Hand grade | Judge passes | Majority | "
        "Agree |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in result["questions"]:
        passes = pass_verdicts(r)
        verdict = majority(passes)
        agree = "yes" if verdict == r["human"]["verdict"] else "no"
        lines.append(
            f"| {r['id']} | {r['category']} | {r['language']} | {short(r['question'])} | "
            f"{r['outcome']} | {r['human']['verdict']} | {' / '.join(passes)} | {verdict} | "
            f"{agree} |"
        )
    return lines


def disagreement_lines(result: Mapping) -> list[str]:
    lines = []
    for r in result["questions"]:
        passes = pass_verdicts(r)
        verdict = majority(passes)
        if verdict == r["human"]["verdict"]:
            continue
        shown = next((j for j, v in zip(r["judge"], passes, strict=True) if v == verdict), None)
        shown = shown or r["judge"][0]
        reasoning = (shown["output"] or {}).get("reasoning", "; ".join(shown["errors"]))
        note = f" ({short(r['human']['note'], 200)})" if r["human"]["note"].strip() else ""
        lines.append(
            f"- {r['id']}: hand grade {r['human']['verdict']}{note}; judge {verdict} "
            f"({' / '.join(passes)}): {short(reasoning, 300)}"
        )
    return lines or ["None."]


def grade_spread_line(summary: Mapping) -> str | None:
    """What kappa and the sample cannot show when the hand grades use few levels."""
    used = [v for v, n in summary["human_counts"].items() if n]
    if len(used) == 1:
        level = LABELS[used[0]].lower()
        return (
            f"Every hand grade is {level}. With one level on one side, chance agreement equals "
            f"the judge's own {level} rate, so kappa is 0 whatever the judge does and says "
            "nothing here: read the exact agreement and the confusion matrix instead. The sample "
            f"also has no answer graded other than {level}, so it does not show whether the "
            "judge agrees with a person on such answers."
        )
    if not summary["human_counts"]["incorrect"]:
        return (
            "No answer is graded incorrect by hand, so the sample does not show whether the "
            "judge agrees with a person on wrong answers."
        )
    return None


def limits_line(summary: Mapping) -> str:
    return (
        f"n = {summary['n']}, so one answer moves the agreement by about "
        f"{100 / summary['n']:.0f} points, and kappa is unstable at this size. The answers come "
        "from the test set with the score gate off. Nothing in the answer system was tuned on "
        "them, and the judge prompt was not changed after the grades. If the judge prompt "
        "changes, calibrate again on new answers."
    )


def notes(summary: Mapping) -> list[str]:
    spread = grade_spread_line(summary)
    return [*([spread, ""] if spread else []), limits_line(summary)]


def report_section(result: Mapping, path: str) -> str:
    summary = summarize(result)
    j = result["settings"]["judge"]
    q = j["prompts"]["quality"]
    lines = [
        f"The quality judge (`{j['model']}`, {q['name']} {q['version']}) against the user's hand "
        f"grades of {summary['n']} answers, graded blind before any judge call (S2-19; rules "
        "in docs/METRICS.md).",
        "",
        *main_tables(summary),
        "",
        *notes(summary),
        "",
        "Per answer and every disagreement with the judge's reasoning: "
        f"[evals/results/calibration.md](evals/results/calibration.md); results `{path}`.",
    ]
    return "\n".join(lines) + "\n"


def markdown(result: Mapping, path: str) -> str:
    summary = summarize(result)
    j = result["settings"]["judge"]
    q = j["prompts"]["quality"]
    commit = result["git"]["commit"] or "unknown"
    dirty = " (uncommitted changes)" if result["git"]["dirty"] else ""
    cost = summary["cost"]
    lines = [
        "# Judge calibration: the quality judge against hand grades (S2-19)",
        "",
        f"Generated by `make calibrate-judge` into `{path}`; "
        "`PYTHONPATH=. uv run python scripts/calibrate_judge.py --report` rebuilds it without "
        "models.",
        "",
        f"Run {result['created_at']} on {result['machine']['platform']}, commit "
        f"`{commit[:12]}`{dirty}. Answers `{result['answers']['path']}` (sha256 "
        f"`{result['answers']['sha256'][:12]}`), hand grades `{result['grades']['path']}` "
        f"(sha256 `{result['grades']['sha256'][:12]}`), test set sha256 "
        f"`{result['test_set']['sha256'][:12]}`.",
        "",
        settings_line(result),
        "",
        f"Judge: model `{j['model']}`, prompt {q['name']} {q['version']} (`{q['sha256']}`), "
        f"{summary['passes']} passes per answer, no temperature (the model takes none). The "
        "user graded every answer by hand from `evals/results/calibration/sheet.md` before the "
        "first judge call. Headline: the hand grade against the judge's majority verdict (2 of "
        "3 passes); with no majority it counts as a disagreement. Lenient: the judge graded "
        "higher than the hand grade (incorrect < partially correct < correct).",
        "",
        *main_tables(summary),
        "",
        *notes(summary),
        "",
        f"Cost: {cost['calls']} judge calls, {cost['prompt_tokens']} prompt and "
        f"{cost['completion_tokens']} completion tokens, ${cost['usd']:.4f} (reported by "
        "OpenRouter).",
        "",
        "## Per answer",
        "",
        "Outcome: the shown answer's status, or why none is shown. Judge passes: the verdict "
        "of each pass, in order.",
        "",
        *question_table(result),
        "",
        "## Disagreements",
        "",
        "Hand grade and note, then the judge's majority verdict, its passes and its reasoning.",
        "",
        *disagreement_lines(result),
    ]
    return "\n".join(lines) + "\n"


def result_row(row: Mapping, question: TestQuestion, grade: Grade, judgements: list) -> dict:
    """One calibration row: the saved answer's outcome, the hand grade and every judge pass."""
    return {
        "id": row["id"],
        "question": question.question,
        "category": question.category.value,
        "language": question.language,
        "outcome": outcome(row),
        "has_claims": bool(shown_claims(row)),
        "human": {"verdict": grade.verdict, "note": grade.note},
        "judge": judgements,
    }
