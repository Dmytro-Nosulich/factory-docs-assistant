"""One `make eval` run on the test set (S2-18): its rows, its rates and its report.

A run is one JSON file in `evals/results/runs/`. Each question row holds what the answer
pipeline showed (`final_status`, the shown answer, the chunks sent), its S2-17 deterministic
scores, and the two judgements of `evals/judges.py`, each with its tokens and cost. Everything
below works on that JSON, so `--report` rebuilds every table without models.
"""

from collections import Counter
from collections.abc import Mapping, Sequence
from dataclasses import asdict

from evals.judges import (
    FAITHFULNESS,
    NO_CLAIMS,
    QUALITY,
    QUALITY_LEVELS,
    SUPPORT_LEVELS,
    SupportVerdict,
    agreement_table,
    claim_verdicts,
    faithfulness_counts,
    quality_counts,
    quality_verdict,
    shown_claims,
)
from evals.scorers import QuestionScore, counts
from factory_docs.answer import shown_answer
from factory_docs.cost import record_tokens
from factory_docs.refusal_eval import cell, short
from factory_docs.run import record_cost
from factory_docs.test_set import Category, TestQuestion

START = "<!-- answers:start (generated by `make eval`; edits here are overwritten) -->"
END = "<!-- answers:end -->"

QUALITY_LABELS = {
    "correct": "Correct",
    "partially_correct": "Partially correct",
    "incorrect": "Incorrect",
    "not_judged": "Not judged",
}
SUPPORT_LABELS = {
    "supported": "Supported",
    "partially_supported": "Partially supported",
    "not_supported": "Not supported",
}


# --- rows ----------------------------------------------------------------------------------


def answer_row(question: TestQuestion, record: Mapping, record_path: str) -> dict:
    """What the answer pipeline did for one test question, from its answer record."""
    answer = shown_answer(dict(record))
    calls = [c for c in (record["call"], (record.get("repair") or {}).get("call")) if c]
    prompt_tokens, completion_tokens = record_tokens(record)
    retrieval = record["retrieval"]
    return {
        "id": question.id,
        "question": question.question,
        "language": question.language,
        "category": question.category.value,
        "top_score": retrieval["top_score"],
        "sent": [source["chunk_id"] for source in retrieval["sent"]],
        "dropped": retrieval["dropped"],
        "final_status": record["final_status"],
        "answer": answer,
        "cost_usd": record_cost(dict(record)),
        "prompt_tokens": prompt_tokens,
        "completion_tokens": completion_tokens,
        "total_s": sum(c.get("total_s") or 0 for c in calls) if calls else None,
        "record": record_path,
        "errors": [] if answer else (record.get("repair") or record)["errors"],
    }


def score_dict(score: QuestionScore) -> dict:
    return {**asdict(score), "category": score.category.value}


def score_from_dict(data: Mapping) -> QuestionScore:
    return QuestionScore(**{**data, "category": Category(data["category"])})


def judgement_summary(judgement: Mapping, record_path: str | None) -> dict:
    """The part of a judge record kept in the run file; the raw reply only when invalid."""
    prompt_tokens, completion_tokens = record_tokens(judgement)
    out = {
        "status": judgement["status"],
        "output": judgement["output"],
        "errors": judgement["errors"],
        "cost_usd": record_cost(dict(judgement)),
        "prompt_tokens": prompt_tokens,
        "completion_tokens": completion_tokens,
        "record": record_path,
    }
    if judgement["status"] == "invalid":
        out["raw"] = judgement["raw"]
    return out


# --- rates ---------------------------------------------------------------------------------


def group_rates(rows: Sequence[Mapping]) -> dict:
    return {
        "questions": len(rows),
        "deterministic": counts([score_from_dict(r["score"]) for r in rows]),
        "quality": quality_counts([r[QUALITY] for r in rows]),
        "faithfulness": faithfulness_counts([r[FAITHFULNESS] for r in rows]),
    }


def phase_cost(rows: Sequence[Mapping], key: str | None) -> dict:
    """Calls, tokens and reported cost of one phase: the answers (key None) or a judge."""
    if key is None:
        parts = rows
        calls = sum(r["total_s"] is not None for r in rows)
    else:
        parts = [r[key] for r in rows]
        calls = sum(p["status"] != NO_CLAIMS for p in parts)
    usd = sum(p["cost_usd"] for p in parts)
    return {
        "calls": calls,
        "prompt_tokens": sum(p["prompt_tokens"] for p in parts),
        "completion_tokens": sum(p["completion_tokens"] for p in parts),
        "usd": usd,
        "usd_per_1000": 1000 * usd / len(rows) if rows else None,
    }


def summarize(run: Mapping) -> dict:
    """Every number of the report, from the saved run."""
    rows = run["questions"]
    categories = [c.value for c in Category if any(r["category"] == c.value for r in rows)]
    languages = sorted({r["language"] for r in rows})
    cost = {
        "answers": phase_cost(rows, None),
        QUALITY: phase_cost(rows, QUALITY),
        FAITHFULNESS: phase_cost(rows, FAITHFULNESS),
    }
    judges = cost[QUALITY]["usd"] + cost[FAITHFULNESS]["usd"]
    cost["judges_usd"] = judges
    cost["judges_usd_per_1000"] = 1000 * judges / len(rows) if rows else None
    cost["spent_this_run_usd"] = judges + (0.0 if run["answers_from"] else cost["answers"]["usd"])
    return {
        "overall": group_rates(rows),
        "by_category": {
            c: group_rates([r for r in rows if r["category"] == c]) for c in categories
        },
        "by_language": {
            lang: group_rates([r for r in rows if r["language"] == lang]) for lang in languages
        },
        "agreement": agreement_table(
            [r["score"]["passed"] for r in rows], [r[QUALITY] for r in rows]
        ),
        "cost": cost,
    }


# --- rendering -----------------------------------------------------------------------------


def outcome_of(row: Mapping) -> str:
    return row["score"]["outcome"]


def categories_line(rows: Sequence[Mapping]) -> str:
    kinds = Counter(r["category"] for r in rows)
    languages = Counter(r["language"] for r in rows)
    return (
        ", ".join(f"{kinds[c.value]} {c.value}" for c in Category if kinds[c.value])
        + "; languages "
        + ", ".join(f"{lang} {n}" for lang, n in languages.most_common())
    )


def settings_line(run: Mapping) -> str:
    a = run["settings"]["answer"]
    gate = "off" if a["min_rerank_score"] is None else f"on at {a['min_rerank_score']}"
    return (
        f"Answered like `make ask`: model `{a['model']}`, prompt {a['prompt']['name']} "
        f"{a['prompt']['version']}; search `{a['collection']}`, {a['mode']} + rerank "
        f"(`{a['reranker']}`), best {a['k']} hits, context budget {a['max_context_tokens']} "
        f"estimated tokens, score gate {gate}, no filter."
    )


def judge_line(run: Mapping) -> str:
    j = run["settings"]["judge"]
    q, f = j["prompts"][QUALITY], j["prompts"][FAITHFULNESS]
    return (
        f"Judges: model `{j['model']}`, prompts {q['name']} {q['version']} and "
        f"{f['name']} {f['version']}; one run, no temperature (the model takes none)."
    )


def table_rows(summary: Mapping) -> list[tuple[str, Mapping]]:
    return [("all", summary["overall"]), *summary["by_category"].items()]


def deterministic_table(summary: Mapping) -> list[str]:
    lines = [
        "| Category | Questions | Passed | Unanswerable refused | Answerable refused "
        "| Right source | Evidence cited | All key facts | Forbidden fact stated "
        "| Wrong doc cited |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name, g in table_rows(summary):
        d = g["deterministic"]
        lines.append(
            f"| {name} | {g['questions']} | {cell(d['passed'])} "
            f"| {cell(d['unanswerable_refused'])} | {cell(d['answerable_refused'])} "
            f"| {cell(d['right_source'])} | {cell(d['evidence_cited'])} "
            f"| {cell(d['all_facts'])} | {cell(d['forbidden'])} | {cell(d['wrong_source'])} |"
        )
    return lines


def quality_table(summary: Mapping) -> list[str]:
    lines = [
        "| Category | " + " | ".join(QUALITY_LABELS[level] for level in QUALITY_LEVELS) + " |",
        "|---|" + "---|" * len(QUALITY_LEVELS),
    ]
    for name, g in table_rows(summary):
        q = g["quality"]
        lines.append(f"| {name} | " + " | ".join(cell(q[lv]) for lv in QUALITY_LEVELS) + " |")
    return lines


def faithfulness_table(summary: Mapping) -> list[str]:
    lines = [
        "| Category | Claims "
        + " | ".join(SUPPORT_LABELS[level].lower() for level in SUPPORT_LEVELS)
        + " | Answers with every claim supported | Answers not judged |",
        "|---|" + "---|" * (len(SUPPORT_LEVELS) + 2),
    ]
    for name, g in table_rows(summary):
        f = g["faithfulness"]
        cells = [cell(f[f"claims_{level}"]) for level in SUPPORT_LEVELS]
        lines.append(
            f"| {name} | "
            + " | ".join(cells)
            + f" | {cell(f['answers_all_supported'])} | {cell(f['answers_not_judged'])} |"
        )
    return lines


def language_table(summary: Mapping) -> list[str]:
    lines = [
        "| Language | Questions | Passed | Judge: correct | Claims supported |",
        "|---|---|---|---|---|",
    ]
    for lang, g in summary["by_language"].items():
        lines.append(
            f"| {lang} | {g['questions']} | {cell(g['deterministic']['passed'])} "
            f"| {cell(g['quality']['correct'])} "
            f"| {cell(g['faithfulness']['claims_supported'])} |"
        )
    return lines


def agreement_lines(summary: Mapping) -> list[str]:
    table = summary["agreement"]
    lines = [
        "| Deterministic (S2-17) | "
        + " | ".join(f"Judge: {QUALITY_LABELS[lv].lower()}" for lv in QUALITY_LEVELS)
        + " |",
        "|---|" + "---|" * len(QUALITY_LEVELS),
    ]
    for name in ("passed", "failed"):
        lines.append(
            f"| {name} | " + " | ".join(str(table[name][lv]) for lv in QUALITY_LEVELS) + " |"
        )
    return lines


def cost_table(summary: Mapping, answers_from: str | None) -> list[str]:
    cost = summary["cost"]
    answers_label = "Answers" + (f" (made by `{answers_from}`)" if answers_from else "")
    lines = [
        "| Phase | Calls | Prompt tokens | Completion tokens | Cost | $ / 1000 questions |",
        "|---|---|---|---|---|---|",
    ]
    for label, key in (
        (answers_label, "answers"),
        ("Quality judge", QUALITY),
        ("Faithfulness judge", FAITHFULNESS),
    ):
        c = cost[key]
        lines.append(
            f"| {label} | {c['calls']} | {c['prompt_tokens']} | {c['completion_tokens']} "
            f"| ${c['usd']:.4f} | ${c['usd_per_1000']:.2f} |"
        )
    return lines


def main_tables(run: Mapping, summary: Mapping) -> list[str]:
    rows = run["questions"]
    cost = summary["cost"]
    return [
        f"{len(rows)} test questions from `{run['test_set']['path']}` ({categories_line(rows)}). "
        f"{settings_line(run)} {judge_line(run)} Rules in docs/METRICS.md. One question is "
        f"1/{len(rows)} of the overall rates and 1/5 to 1/8 of a category's, so small "
        "differences are noise.",
        "",
        "**Deterministic scores (S2-17).** Passed: an unanswerable question is refused; any "
        "other is answered, cites an evidence document and states every key fact, and a trap "
        "states no forbidden fact. Wrong doc cited is reported only.",
        "",
        *deterministic_table(summary),
        "",
        "**LLM judge, answer quality.** The shown answer against the reference answer; a "
        'refusal counts as the answer "not in the documents".',
        "",
        *quality_table(summary),
        "",
        "**LLM judge, faithfulness.** Every claim of a shown answer against all chunks sent to "
        "the answer model. Refusals have no claims and are left out.",
        "",
        *faithfulness_table(summary),
        "",
        "Per question language:",
        "",
        *language_table(summary),
        "",
        "Deterministic pass against the quality judge, in questions. Not a calibration: S2-19 "
        "compares the judge with hand grades.",
        "",
        *agreement_lines(summary),
        "",
        "Cost (reported by OpenRouter per call):",
        "",
        *cost_table(summary, run["answers_from"]),
        "",
        f"The judges cost ${cost['judges_usd']:.4f} for {len(rows)} questions, "
        f"${cost['judges_usd_per_1000']:.2f} per 1000; this run spent "
        f"${cost['spent_this_run_usd']:.4f}.",
    ]


def flag(value: bool | None) -> str:
    return "-" if value is None else ("yes" if value else "no")


def question_table(run: Mapping) -> list[str]:
    lines = [
        "| ID | Category | Lang | Question | Top score | Outcome | Passed | Key facts "
        "| Judge | Claims supported |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in run["questions"]:
        s = r["score"]
        facts = f"{sum(s['facts'])}/{len(s['facts'])}" if s["facts"] else "-"
        verdicts = claim_verdicts(r[FAITHFULNESS])
        if verdicts is None:
            support = "not judged"
        elif not verdicts:
            support = "-"
        else:
            support = f"{verdicts.count(SupportVerdict.supported)}/{len(verdicts)}"
        top = "-" if r["top_score"] is None else f"{r['top_score']:.2f}"
        lines.append(
            f"| {r['id']} | {r['category']} | {r['language']} | {short(r['question'])} | {top} "
            f"| {outcome_of(r)} | {flag(s['passed'])} | {facts} "
            f"| {quality_verdict(r[QUALITY])} | {support} |"
        )
    return lines


def unsupported_lines(run: Mapping) -> list[str]:
    lines = []
    for r in run["questions"]:
        judgement = r[FAITHFULNESS]
        if claim_verdicts(judgement) is None:
            lines.append(f"- {r['id']}: not judged ({'; '.join(judgement['errors'])})")
            continue
        texts = [claim["text"] for claim in shown_claims(r)]
        for entry in (judgement["output"] or {}).get("claims", []):
            if entry["verdict"] != SupportVerdict.supported:
                text = short(texts[entry["claim"] - 1], 120)
                lines.append(
                    f'- {r["id"]} claim {entry["claim"]} ({entry["verdict"]}): "{text}". '
                    f"Judge: {short(entry['reasoning'], 300)}"
                )
    return lines or ["None."]


def disagreement_lines(run: Mapping) -> list[str]:
    """Questions where the deterministic pass and the judge's `correct` disagree."""
    lines = []
    for r in run["questions"]:
        verdict = quality_verdict(r[QUALITY])
        if r["score"]["passed"] == (verdict == "correct"):
            continue
        reasoning = (r[QUALITY]["output"] or {}).get("reasoning", "; ".join(r[QUALITY]["errors"]))
        passed = "passed" if r["score"]["passed"] else "failed"
        lines.append(f"- {r['id']} ({passed}, judge {verdict}): {short(reasoning, 300)}")
    return lines or ["None."]


def report_section(run: Mapping, run_path: str) -> str:
    summary = summarize(run)
    lines = main_tables(run, summary)
    lines += [
        "",
        "Per question, unsupported claims and disagreements: "
        f"[evals/results/eval.md](evals/results/eval.md); run file `{run_path}`.",
    ]
    return "\n".join(lines) + "\n"


def markdown(run: Mapping, run_path: str) -> str:
    summary = summarize(run)
    a, j = run["settings"]["answer"], run["settings"]["judge"]
    prompts = ", ".join(
        f"{p['name']} {p['version']} (`{p['sha256']}`)"
        for p in (a["prompt"], a["repair_prompt"], *j["prompts"].values())
    )
    source = f" Answers copied from `{run['answers_from']}`." if run["answers_from"] else ""
    commit = run["git"]["commit"] or "unknown"
    dirty = " (uncommitted changes)" if run["git"]["dirty"] else ""
    lines = [
        "# Answers to the test set: deterministic scores, LLM judge and faithfulness (S2-18)",
        "",
        f"Generated by `make eval` from `{run_path}`; "
        "`PYTHONPATH=. uv run python scripts/eval_answers.py --report` rebuilds it without "
        "models.",
        "",
        f"Run {run['created_at']} on {run['machine']['platform']}, commit `{commit[:12]}`"
        f"{dirty}.{source} Test set sha256 `{run['test_set']['sha256'][:12]}`, chunks sha256 "
        f"`{run['chunks']['sha256'][:12]}`; prompts {prompts}.",
        "",
        *main_tables(run, summary),
        "",
        "## Per question",
        "",
        "Top score: the best hit's reranker score (the gate compares it with the threshold). "
        "Outcome: the shown answer's status, or why none is shown. Key facts: found in the "
        "claim texts. Judge: the quality verdict. Claims supported: by the faithfulness judge.",
        "",
        *question_table(run),
        "",
        "## Claims the faithfulness judge did not find fully supported",
        "",
        *unsupported_lines(run),
        "",
        "## Where the deterministic pass and the judge disagree",
        "",
        "Passed but not judged correct, or failed but judged correct, with the judge's reasoning.",
        "",
        *disagreement_lines(run),
    ]
    return "\n".join(lines) + "\n"
