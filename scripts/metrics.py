"""Print the step 2 metrics table of one or more runs, S1-11 (rules in docs/METRICS.md).

Usage: uv run python scripts/metrics.py [--out FILE] [RUN_ID ...]
With no run IDs, every run under results/runs/. Reads only saved results: no model calls.
--out also writes the tables to FILE (S1-12, `make comparison`), with no timestamp, so the
same runs always give the same file.
"""

import argparse
import sys
from pathlib import Path

from factory_docs.config import load_config
from factory_docs.metrics import format_tables, run_metrics
from factory_docs.run import RUNS, SUMMARY


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("run_ids", nargs="*", help="directory names under results/runs/")
    parser.add_argument("--out", type=Path, help="also write the tables to this Markdown file")
    args = parser.parse_args()
    run_ids = args.run_ids or sorted(p.parent.name for p in RUNS.glob(f"*/{SUMMARY}"))
    missing = [r for r in run_ids if not (RUNS / r / SUMMARY).exists()]
    if missing:
        sys.exit(f"no {SUMMARY} in results/runs/ for: {', '.join(missing)}")
    if not run_ids:
        sys.exit("no runs in results/runs/: run `make run` first")
    config = load_config()
    tables = format_tables([run_metrics(RUNS / run_id, config) for run_id in run_ids])
    print(tables)
    if args.out:
        header = [
            "# Metrics comparison",
            "",
            "Generated by `make comparison` (`scripts/metrics.py`) from the saved results of these "
            "runs in `results/runs/`; re-running it calls no model.",
            "",
            *(f"- `{run_id}`" for run_id in run_ids),
        ]
        args.out.write_text("\n".join(header) + "\n\n" + tables + "\n", encoding="utf-8")
        print(f"\nsaved: {args.out}")


if __name__ == "__main__":
    main()
